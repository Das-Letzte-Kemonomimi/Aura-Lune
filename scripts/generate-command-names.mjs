#!/usr/bin/env node
// Generates `src/api/commands.generated.ts`: a union of the names of every Tauri command
// registered in `src-tauri/src/lib.rs` (`tauri::generate_handler![...]`).
//
// Run after adding or removing a command:  npm run gen:commands
// `src-tauri/tests/ipc_contract_test.rs` checks that the file stays in sync.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const libRs = fs.readFileSync(path.join(root, 'src-tauri/src/lib.rs'), 'utf8');
const start = libRs.indexOf('generate_handler![');
if (start < 0) throw new Error('generate_handler! not found in lib.rs');
const body = libRs.slice(start + 'generate_handler!['.length, libRs.indexOf(']', start));
const names = [...new Set(
  body
    .split(',')
    .map((s) => s.replace(/\/\/.*$/gm, '').trim())
    .filter(Boolean)
    .map((s) => s.split('::').pop()),
)].sort();

const out = `// AUTO-GENERATED by scripts/generate-command-names.mjs — do not edit by hand.
// Source: src-tauri/src/lib.rs (tauri::generate_handler!). Regenerate: npm run gen:commands

export const COMMAND_NAMES = [
${names.map((n) => `  '${n}',`).join('\n')}
] as const;

export type CommandName = (typeof COMMAND_NAMES)[number];
`;
fs.writeFileSync(path.join(root, 'src/api/commands.generated.ts'), out);
console.log(`Wrote ${names.length} command names to src/api/commands.generated.ts`);
